function isPointOnSegment(point: LatLng, start: Position, end: Position) {
  const lengthSquared =
    (end[0] - start[0]) ** 2 + (end[1] - start[1]) ** 2;
  if (lengthSquared === 0) {
    return Math.abs(point.lng - start[0]) <= 1e-10 && Math.abs(point.lat - start[1]) <= 1e-10;
  }
  const cross =
    (point.lng - start[0]) * (end[1] - start[1]) -
    (point.lat - start[1]) * (end[0] - start[0]);
  if (Math.abs(cross) > 1e-10) return false;
  const dot =
    (point.lng - start[0]) * (end[0] - start[0]) +
    (point.lat - start[1]) * (end[1] - start[1]);
  if (dot < 0) return false;
  return dot <= lengthSquared;
}

function isPointInRing(point: LatLng, ring: Position[]) {
  let inside = false;
  for (let index = 0, previous = ring.length - 1; index < ring.length; previous = index++) {
    const start = ring[previous];
    const end = ring[index];
    if (isPointOnSegment(point, start, end)) return true;
    const crossesLatitude = (start[1] > point.lat) !== (end[1] > point.lat);
    if (
      crossesLatitude &&
      point.lng < ((end[0] - start[0]) * (point.lat - start[1])) / (end[1] - start[1]) + start[0]
    ) {
      inside = !inside;
    }
  }
  return inside;
}

export function isWithinMetroManila(
  lat: number | null | undefined,
  lng: number | null | undefined
): boolean {
  if (!Number.isFinite(lat) || !Number.isFinite(lng)) return false;
  const point = { lat: Number(lat), lng: Number(lng) };
  if (
    point.lat < METRO_MANILA_BOUNDS.minLat ||
    point.lat > METRO_MANILA_BOUNDS.maxLat ||
    point.lng < METRO_MANILA_BOUNDS.minLng ||
    point.lng > METRO_MANILA_BOUNDS.maxLng ||
    (point.lat === 0 && point.lng === 0)
  ) {
    return false;
  }
  return NCR_RINGS.some((ring) => isPointInRing(point, ring));
}

export function getRouteLocationCoordinates(value: unknown): LatLng | null {
  if (!value || typeof value !== "object" || Array.isArray(value)) return null;
  const point = value as Record<string, unknown>;
  const rawLat = point.lat ?? point.latitude;
  const rawLng = point.lng ?? point.lon ?? point.longitude;
  if (rawLat == null || rawLng == null || rawLat === "" || rawLng === "") return null;
  const lat = Number(rawLat);
  const lng = Number(rawLng);
  return Number.isFinite(lat) && Number.isFinite(lng) ? { lat, lng } : null;
}
